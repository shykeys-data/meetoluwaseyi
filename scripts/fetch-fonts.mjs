// Downloads the four site fonts (latin subset, woff2) from Google Fonts into public/fonts and writes
// src/web/styles/fonts.css, so the live site self-hosts them: no third-party request, no tracking,
// and font-src 'self' in the CSP. Runs in CI before the build (this repo's workspace can't reach Google).
import { mkdir, writeFile } from 'node:fs/promises';

const FAMILIES = [
  'Outfit:wght@300..900',
  'Caveat:wght@400..700',
  'Instrument+Serif:ital@0;1',
  'Geist:wght@300..600',
];
// A modern browser user agent makes Google answer with woff2.
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';

const slug = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

async function main() {
  await mkdir('public/fonts', { recursive: true });
  const out = ['/* Generated by scripts/fetch-fonts.mjs: self-hosted, latin subset only. */'];
  for (const fam of FAMILIES) {
    const res = await fetch(`https://fonts.googleapis.com/css2?family=${fam}&display=swap`, {
      headers: { 'User-Agent': UA },
    });
    if (!res.ok) throw new Error(`Google Fonts answered ${res.status} for ${fam}`);
    const css = await res.text();
    // Keep only the /* latin */ blocks.
    const blocks = [...css.matchAll(/\/\* latin \*\/\s*@font-face\s*\{([^}]+)\}/g)];
    if (blocks.length === 0) throw new Error(`No latin block for ${fam}:\n${css.slice(0, 600)}`);
    for (const m of blocks) {
      const block = m[1];
      const pick = (name, re, fallback) => {
        const hit = re.exec(block)?.[1];
        if (hit !== undefined) return hit.trim();
        if (fallback !== undefined) return fallback;
        throw new Error(`No ${name} in the ${fam} block:\n${block}`);
      };
      const family = pick('font-family', /font-family:\s*['"]?([^;'"]+)['"]?;/);
      const style = pick('font-style', /font-style:\s*(\w+)/, 'normal');
      const weight = pick('font-weight', /font-weight:\s*([\d ]+)/, '400');
      const url = pick('font url', /src:\s*url\(['"]?(https:[^)'"]+)['"]?\)/);
      const range = pick('unicode-range', /unicode-range:\s*([^;]+);/);
      const file = `${slug(family)}-${weight.replace(/\s+/g, '-')}-${style}.woff2`;
      const font = await fetch(url, { headers: { 'User-Agent': UA } });
      if (!font.ok) throw new Error(`Font download failed for ${family}`);
      await writeFile(`public/fonts/${file}`, Buffer.from(await font.arrayBuffer()));
      out.push(
        `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:swap;src:url(/fonts/${file}) format('woff2');unicode-range:${range}}`,
      );
      console.log('font', file);
    }
  }
  await writeFile('src/web/styles/fonts.css', out.join('\n') + '\n');
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
